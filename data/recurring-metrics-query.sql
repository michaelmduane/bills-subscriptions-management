-- Key metrics: recurring vs non-recurring decline rates, GPV, customer counts
SELECT 
  COUNT(DISTINCT CASE WHEN IS_RECURRING = 'true' AND STATE = 'SETTLED' THEN TRANSACTION_TOKEN END) as recurring_settled_txns,
  COUNT(DISTINCT CASE WHEN IS_RECURRING = 'true' AND STATE = 'DECLINED' THEN TRANSACTION_TOKEN END) as recurring_declined_txns,
  COUNT(DISTINCT CASE WHEN IS_RECURRING = 'true' AND STATE = 'SETTLED' THEN CUSTOMER_TOKEN END) as recurring_active_customers,
  COUNT(DISTINCT CASE WHEN STATE = 'SETTLED' THEN CUSTOMER_TOKEN END) as total_card_active_customers,
  SUM(CASE WHEN IS_RECURRING = 'true' AND STATE = 'SETTLED' THEN SETTLED_TRANSACTION_AMOUNT_CENTS END) / 100.0 as recurring_gpv_dollars,
  SUM(CASE WHEN STATE = 'SETTLED' THEN SETTLED_TRANSACTION_AMOUNT_CENTS END) / 100.0 as total_gpv_dollars,
  SUM(CASE WHEN IS_RECURRING = 'true' AND STATE = 'SETTLED' THEN SETTLED_TRANSACTION_AMOUNT_CENTS END) / 100.0 / 
    NULLIF(COUNT(DISTINCT CASE WHEN IS_RECURRING = 'true' AND STATE = 'SETTLED' THEN CUSTOMER_TOKEN END), 0) as avg_recurring_gpv_per_customer,
  COUNT(DISTINCT CASE WHEN IS_RECURRING = 'true' AND STATE = 'SETTLED' THEN TRANSACTION_TOKEN END) * 1.0 / 
    NULLIF(COUNT(DISTINCT CASE WHEN IS_RECURRING = 'true' AND STATE = 'SETTLED' THEN CUSTOMER_TOKEN END), 0) as avg_recurring_txns_per_customer,
  COUNT(DISTINCT CASE WHEN IS_RECURRING = 'true' AND STATE = 'DECLINED' THEN TRANSACTION_TOKEN END) * 100.0 / 
    NULLIF(COUNT(DISTINCT CASE WHEN IS_RECURRING = 'true' THEN TRANSACTION_TOKEN END), 0) as recurring_decline_rate_pct,
  COUNT(DISTINCT CASE WHEN (IS_RECURRING IS NULL OR IS_RECURRING != 'true') AND STATE = 'DECLINED' THEN TRANSACTION_TOKEN END) * 100.0 / 
    NULLIF(COUNT(DISTINCT CASE WHEN (IS_RECURRING IS NULL OR IS_RECURRING != 'true') THEN TRANSACTION_TOKEN END), 0) as non_recurring_decline_rate_pct
FROM APP_CASH.APP.CASH_CARD_TRANSACTIONS
WHERE CREATED_AT >= DATEADD(month, -3, CURRENT_DATE);


-- Top recurring merchants by customer count
SELECT 
  PARENT_MERCHANT_NAME,
  COUNT(DISTINCT CUSTOMER_TOKEN) as unique_customers,
  COUNT(DISTINCT TRANSACTION_TOKEN) as total_txns,
  SUM(CASE WHEN STATE = 'SETTLED' THEN SETTLED_TRANSACTION_AMOUNT_CENTS END) / 100.0 as settled_gpv,
  COUNT(DISTINCT CASE WHEN STATE = 'DECLINED' THEN TRANSACTION_TOKEN END) * 100.0 / COUNT(DISTINCT TRANSACTION_TOKEN) as decline_rate_pct
FROM APP_CASH.APP.CASH_CARD_TRANSACTIONS
WHERE IS_RECURRING = 'true'
  AND CREATED_AT >= DATEADD(month, -3, CURRENT_DATE)
  AND PARENT_MERCHANT_NAME IS NOT NULL
GROUP BY PARENT_MERCHANT_NAME
ORDER BY unique_customers DESC
LIMIT 20;
